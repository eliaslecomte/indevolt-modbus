"""Generate explicit component models from the reviewed register catalog."""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]


def identifier(value: str) -> str:
    """Normalize a source label to a Python identifier."""
    result = re.sub("[^A-Z0-9]+", "_", value.upper()).strip("_")
    return "VALUE_" + result if result[:1].isdigit() else result


def main() -> None:
    """Render deterministic source files; run Ruff after generation."""
    rows: list[dict[str, Any]] = json.loads((ROOT / "docs/registers.json").read_text())
    target = ROOT / "src/indevolt_modbus"
    enums = [
        '"""Documented register enumerations (generated by script/generate.py)."""',
        "from enum import IntEnum",
        "",
    ]
    components = [
        '"""Typed functional components (generated by script/generate.py)."""',
        "from modbus_connection.model import NumberField, enum",
        "from .model import IndevoltComponent",
        "from .validation import validator",
        "from . import enums",
        "",
    ]
    groups: dict[str, list[dict[str, Any]]] = {}
    metadata = [
        '"""Register metadata (generated by script/generate.py)."""',
        "from .model import Register",
        "",
        "REGISTERS: tuple[Register, ...] = (",
    ]
    for row in rows:
        if "deferred" in row:
            continue
        groups.setdefault(row["component"], []).append(row)
        options = row["options"] if row["data_type"] != "bitfield32" else {}
        name = f"Register{row['address']}"
        if options:
            enums += [f"class {name}(IntEnum):", f'    """{row["name"]}."""']
            for code, option in options.items():
                enums.append(f"    {identifier(option['name'])} = {code}")
            enums.append("")
        metadata.append(
            "    Register("
            + ", ".join(
                f"{k}={v!r}"
                for k, v in {
                    "key": row["key"],
                    "component": row["component"],
                    "name": row["name"],
                    "address": row["address"],
                    "unit": row["unit"],
                    "group": row["group"],
                    "minimum_version": row["version"],
                    "writable": row["access"] == "RW",
                    "options": {int(k): v["name"] for k, v in options.items()},
                    "option_versions": {
                        int(k): v["version"] for k, v in options.items()
                    },
                }.items()
            )
            + "),"
        )
    metadata.append(")")
    for group, fields in groups.items():
        cls = "".join(s.title() for s in group.split("_"))
        components += [
            f"class {cls}(IndevoltComponent):",
            f'    """{group.replace("_", " ").capitalize()}."""',
        ]
        for row in fields:
            address = row["address"]
            opts = row["options"] if row["data_type"] != "bitfield32" else {}
            writable = f"validator({address})" if row["access"] == "RW" else "False"
            if opts:
                expr = f"enum({address}, enums.Register{address}, writable={writable})"
            else:
                count = (
                    2
                    if row["data_type"] in ("uint32", "int32", "bitfield32", "acc32")
                    else 1
                )
                signed = row["data_type"].startswith("int")
                typ = "float" if row["scale"] != 1 else "int"
                expr = (
                    f"NumberField[{typ}]({address}, count={count}, signed={signed}, "
                    f"scale={row['scale']}, unit={row['unit']!r}, writable={writable})"
                )
            components.append(f"    {row['key']} = {expr}")
        components.append("")
    components.append("COMPONENTS: dict[str, type[IndevoltComponent]] = {")
    components += [
        f"    {g!r}: " + "".join(s.title() for s in g.split("_")) + "," for g in groups
    ]
    components.append("}")
    for file, lines in [
        ("enums.py", enums),
        ("components.py", components),
        ("registers.py", metadata),
    ]:
        (target / file).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
